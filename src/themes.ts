export function applyTheme(index: number) {
  const theme = themes[index] ?? themes[0];
  for (const token of [
    'bg',
    'panel',
    'raised',
    'text',
    'muted',
    'accent',
    'border',
  ] as const)
    document.documentElement.style.setProperty(`--${token}`, theme[token]);
  document.documentElement.dataset.mode = theme.dark ? 'dark' : 'light';
  document.documentElement.style.colorScheme = theme.dark ? 'dark' : 'light';
}
